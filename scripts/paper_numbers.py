"""Generate paper/numbers.tex (LaTeX macros) from results/v2/summary.json, so every number in the
paper is reproducible from the scripts.  python scripts/paper_numbers.py"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt(x, nd=2):
    if x is None:
        return "--"
    if isinstance(x, (list, tuple)):
        x = x[0]
    try:
        x = float(x)
    except (TypeError, ValueError):
        return str(x)
    if x != x:
        return "--"
    return f"{x:.{nd}f}"


def ci(v, nd=2):
    if not isinstance(v, (list, tuple)) or len(v) < 3:
        return fmt(v, nd)
    return f"{fmt(v[0], nd)}\\,[{fmt(v[1], nd)}, {fmt(v[2], nd)}]"


DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven",
          "8": "Eight", "9": "Nine"}


def name(s):
    """Key -> LaTeX macro name (letters only; digits spelled out): 'H3_rec' -> 'HThreeRec'."""
    s = "".join(DIGITS.get(ch, ch) for ch in s.title())
    return re.sub(r"[^A-Za-z]", "", s)


def main():
    S = json.loads((ROOT / "results" / "v2" / "summary.json").read_text())
    L = ["% generated by scripts/paper_numbers.py -- do not edit"]
    fam_tag = {"rec": "Rec", "jepa": "Jepa", "state": "State"}
    for f, F in fam_tag.items():
        tag = f"{f}_M_gru_train_100000"
        o = S["configs"].get(tag)
        if not o:
            continue
        import numpy as np
        mean = lambda k: float(np.mean([v for v in o[k] if v is not None])) if o.get(k) else float("nan")
        vals = {
            "Seeds": str(o["n_seeds"]),
            "Gate": "passes" if o["gate_pass"] else "fails",
            "Slope": fmt(mean("geff_slope")),
            "RtwoG": fmt(mean("r2_g_trained")), "RtwoGun": fmt(mean("r2_g_untrained")),
            "RtwoE": fmt(mean("r2_E_trained")), "RtwoPx": fmt(mean("r2_px_trained")),
            "ErrEight": fmt(mean("err8_px"), 1), "ErrTest": fmt(mean("test_err_px"), 1),
            "NatS": ci(o["nat_s"]), "NatHi": ci(o["nat_hi"]), "NatLo": ci(o["nat_lo"]),
            "InfHi": ci(o["inf_hi"]), "InfLo": ci(o["inf_lo"]),
            "ExeS": ci(o["exe_s"]), "ExeHi": ci(o["exe_hi"]), "ExeLo": ci(o["exe_lo"]),
            "Cer": ci(o["cer_in_range"]), "Spec": fmt(o["spec_px_in_range"]),
            "InvHHi": ci(o["inv_h_hi"]), "InvHLo": ci(o["inv_h_lo"]),
            "InvZHi": ci(o["inv_z_hi"]), "InvZLo": ci(o["inv_z_lo"]),
            "InvNatHi": ci(o["inv_nat_hi"]), "InvNatLo": ci(o["inv_nat_lo"]),
            "AntiH": ci(o["inv_h_anti_geff"]), "AntiZ": ci(o["inv_z_anti_geff"]),
            "LocusHi": o["locus_hi"], "LocusLo": o["locus_lo"],
            "CtxErr": fmt(o.get("ctx_readout_err_px"), 2),
        }
        for k in ("lambda_nat_hi", "lambda_nat_lo", "lambda_steer_hi", "lambda_steer_lo", "lambda_inv_h_hi",
                  "lambda_inv_h_lo", "lambda_inv_z_hi", "lambda_inv_z_lo", "lambda_inv_nat_hi", "lambda_inv_nat_lo"):
            if k in o:
                vals[name(k)] = ci(o[k])
        if "perception_ood_excess_px" in o:
            vals["PercExcess"] = ci(o["perception_ood_excess_px"])
        if "drift_E_median_by_chunk" in o:
            d = o["drift_E_median_by_chunk"]
            vals["DriftOne"], vals["DriftFour"] = fmt(d[0]), fmt(d[-1])
        for k, v in vals.items():
            L.append(f"\\newcommand{{\\{F}{k}}}{{{v}}}")
    for k, v in S.get("pvals_holm", {}).items():
        L.append(f"\\newcommand{{\\P{name(k)}}}{{{fmt(v, 3)}}}")
    for k, v in S.items():
        if k.startswith("H4_"):
            F = fam_tag[k[3:]]
            L.append(f"\\newcommand{{\\{F}HfourRho}}{{{ci(v['slope_rho_hi_per_decade'])}}}")
            L.append(f"\\newcommand{{\\{F}HfourErr}}{{{ci(v['slope_test_err_px_per_decade'])}}}")
    (ROOT / "paper" / "numbers.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
